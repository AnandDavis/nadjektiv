/**
 * Nouns with their gender and plural: the noun cards topic, and the "new word" card
 * shown the first time a noun comes up in a quiz.
 *
 * NOUN_CARDS is append-only: a card's position gives its question id
 * (`noun-cards-gap-<n>`), which is stored in learners' progress. Check every plural
 * against docs/grammar/ (Plurals) before adding one.
 */

export type Gender = 'der' | 'die' | 'das';

export interface Noun {
  word: string;
  gender: Gender;
  /** `null` for nouns that are normally used without a plural. */
  plural: string | null;
  /** English, singular. */
  gloss: string;
}

export interface NounCard extends Noun {
  plural: string;
  /** English, plural. */
  glossPlural: string;
  /** A tempting wrong plural, used in the options (never shown as correct). */
  wrongPlural: string;
  /** A tempting wrong gender, used in the options. */
  wrongGender: Gender;
  /** The rule that gives this noun its plural, shown after answering. */
  rule: string;
}

